#!/usr/bin/env python3
# @path[tmux/install.py]
# install tmux parts and generate the user tmux.conf.
#
# usage:
#   python3 tmux/install.py
#
# exit codes:
#   0 installed
#   1 install failed

import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

# ==============================================================================
# CONSTANTS
# ==============================================================================

SOURCE = Path(__file__).resolve().parent
PARTS_DIR = "parts"
PARTS = SOURCE / PARTS_DIR
CONFIG_NAME = "tmux.conf"

# insertion order is the tmux load order.
PART_ORDER = {
    "options": "options.conf",
    "palette": "palette.conf",
    "status": "status.conf",
}

CONF_TEMPLATE = """\
# tmux.conf
# generated by [tmux/install.py]; do not edit.
#
# parts load in declared order.

{includes}
"""

# ==============================================================================
# MESSAGES
# ==============================================================================

MESSAGES = {
    "parts.missing": "parts directory is missing at [{path}]",
    "part.missing": "part file is missing at [{path}]",
    "target.file": "target path is not a directory at [{path}]",
    "backup.exists": "backup path already exists at [{path}]",
    "install.failed": "install failed because of [{error}]",
    "reload.failed": "tmux reload failed because of [{error}]",
    "backup.ok": "backup at [{backup}]",
    "install.ok": "installed [{config}]",
}


# ==============================================================================
# TYPES
# ==============================================================================


class InstallError(Exception):
    pass


# ==============================================================================
# HELPERS
# ==============================================================================


def message(key: str, **values: object) -> str:
    return MESSAGES[key].format(**values)


# tmux is posix-only; every supported system uses xdg or ~/.config.
def config_home() -> Path:
    xdg = os.environ.get("XDG_CONFIG_HOME")
    if xdg and Path(xdg).is_absolute():
        return Path(xdg)

    match sys.platform:
        case "win32" | "cygwin" | "msys":
            # windows shells expose a posix home for tmux
            home = os.environ.get("HOME")
            return (Path(home) if home else Path.home()) / ".config"
        case _:
            return Path.home() / ".config"


def part_files() -> list[Path]:
    if not PARTS.is_dir():
        raise InstallError(message("parts.missing", path=PARTS))

    files = [PARTS / name for name in PART_ORDER.values()]
    for path in files:
        if not path.is_file():
            raise InstallError(message("part.missing", path=path))
    return files


def tmux_quote(path: Path) -> str:
    # double quotes keep spaces; escaped characters keep tmux expansion out
    text = path.as_posix()
    for char in ("\\", '"', "$", "~"):
        text = text.replace(char, "\\" + char)
    return f'"{text}"'


def source_line(target: Path, part: Path) -> str:
    return f"source-file {tmux_quote(target / PARTS_DIR / part.name)}"


def backup(target: Path) -> Path | None:
    if not target.exists():
        return None
    if not target.is_dir():
        raise InstallError(message("target.file", path=target))

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    destination = target.with_name(f"{target.name}.bak-{stamp}")
    if destination.exists():
        raise InstallError(message("backup.exists", path=destination))

    shutil.copytree(target, destination)
    return destination


# ==============================================================================
# INSTALL
# ==============================================================================


def install(target: Path, parts: list[Path]) -> Path:
    target.mkdir(parents=True, exist_ok=True)
    shutil.copytree(PARTS, target / PARTS_DIR, dirs_exist_ok=True)

    includes = "\n".join(source_line(target, part) for part in parts)
    content = CONF_TEMPLATE.format(includes=includes)

    config = target / CONFIG_NAME
    temporary = config.with_name(config.name + ".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(config)
    return config


# ==============================================================================
# RELOAD
# ==============================================================================


def reload(config: Path) -> None:
    if shutil.which("tmux") is None:
        return

    probe = subprocess.run(
        ["tmux", "list-sessions"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    if probe.returncode != 0:
        return

    subprocess.run(["tmux", "source-file", str(config)], check=True)


# ==============================================================================
# COMMAND LINE
# ==============================================================================


def main() -> int:
    try:
        parts = part_files()
        target = (config_home() / "tmux").resolve()
        backup_dir = backup(target)
        config = install(target, parts)
    except InstallError as exc:
        print(exc, file=sys.stderr)
        return 1
    except OSError as exc:
        print(message("install.failed", error=exc), file=sys.stderr)
        return 1

    if backup_dir is not None:
        print(message("backup.ok", backup=backup_dir))
    print(message("install.ok", config=config))

    try:
        reload(config)
    except (OSError, subprocess.CalledProcessError) as exc:
        print(message("reload.failed", error=exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
